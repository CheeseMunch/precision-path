export function getCampaignLevel(levelNumber: number): CampaignLevelConfig {
  const found = CAMPAIGN_CONFIG.levels.find((l) => l.levelNumber === levelNumber);
  if (found) return found;
  return CAMPAIGN_CONFIG.levels[0] || DEFAULT_CAMPAIGN_LEVELS[0];
}
